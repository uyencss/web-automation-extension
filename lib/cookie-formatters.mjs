import { CHROME_EPOCH_OFFSET_SECONDS } from './cookie-crypto.mjs';

/**
 * Convert Chrome expires_utc (microseconds since 1601-01-01) to Unix timestamp (seconds).
 */
export function convertChromeExpires(expiresUtc, hasExpires) {
  if (!hasExpires || !expiresUtc) return undefined;
  try {
    const big = BigInt(expiresUtc);
    if (big <= 0n) return undefined;
    return Number((big / 1000000n) - BigInt(CHROME_EPOCH_OFFSET_SECONDS));
  } catch {
    return undefined;
  }
}

/**
 * Map Chrome SameSite integer to standard string.
 */
export function mapSameSite(val) {
  if (val === 1) return 'Lax';
  if (val === 2) return 'Strict';
  if (val === 0) return 'None';
  return undefined; // -1 is Unspecified in Chromium (let browser/client use default)
}

/**
 * Map Chrome priority integer to string.
 */
export function mapPriority(val) {
  if (val === 0) return 'Low';
  if (val === 1) return 'Medium';
  if (val === 2) return 'High';
  return undefined;
}

/**
 * Format a list of cookies into Playwright StorageState format.
 */
export function formatPlaywrightStorageState(cookies) {
  return {
    cookies: cookies.map((c) => ({
      name: c.name,
      value: c.value,
      domain: c.domain || c.hostKey || c.host_key || '',
      path: c.path || '/',
      expires: c.expires !== undefined ? c.expires : -1,
      httpOnly: Boolean(c.httpOnly),
      secure: Boolean(c.secure),
      sameSite: c.sameSite || 'Lax',
    })),
    origins: [],
  };
}

/**
 * Sanitize strings for TSV (Netscape cookies.txt) format.
 * Strips raw tabs and newlines to prevent field injection and layout corruption.
 */
function sanitizeTsvField(val) {
  if (val === undefined || val === null) return '';
  return String(val).replace(/[\t\r\n]+/g, ' ');
}

/**
 * Format a list of cookies into Netscape HTTP Cookie File (cookies.txt) format.
 */
export function formatNetscapeCookies(cookies) {
  const lines = [
    '# Netscape HTTP Cookie File',
    '# Generated by webmcp local-cookie-reader',
    '',
  ];
  for (const c of cookies) {
    const rawDom = sanitizeTsvField(c.domain || c.hostKey || c.host_key || '');
    const dom = c.httpOnly ? `#HttpOnly_${rawDom}` : rawDom;
    const flag = rawDom.startsWith('.') ? 'TRUE' : 'FALSE';
    const path = sanitizeTsvField(c.path || '/');
    const sec = c.secure ? 'TRUE' : 'FALSE';
    const exp = String(c.expires !== undefined && c.expires > 0 ? c.expires : 0);
    const name = sanitizeTsvField(c.name);
    const value = sanitizeTsvField(c.value);
    lines.push(`${dom}\t${flag}\t${path}\t${sec}\t${exp}\t${name}\t${value}`);
  }
  return lines.join('\n') + '\n';
}
